"""Authoring-only font metrics for matching browser/Worker text wrapping.

Requires fontTools. Run from the repository root after preparing the static TTFs.
No Python dependency is used in the deployed Worker or dashboard.
"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont

fonts = {
    "heading": "FourWallsWebsite-SemiBold.ttf",
    "serif": "NotoSerifDisplay-SemiBold.ttf",
    "sans": "Manrope-Regular.ttf",
    "sansBold": "Manrope-SemiBold.ttf",
}
metrics = {}
for name, filename in fonts.items():
    font = TTFont(Path("images/social") / filename)
    cmap, units = font.getBestCmap(), font["head"].unitsPerEm
    advances = font["hmtx"].metrics
    metrics[name] = {
        chr(code): round(advances[glyph][0] / units, 5)
        for code, glyph in cmap.items()
        if 32 <= code <= 0x03FF or 0x1F00 <= code <= 0x206F or code == 0x20AC
    }
output = "// Generated by tools/build-social-font-metrics.py from the self-hosted TTFs.\n"
output += "export const SOCIAL_FONT_METRICS = " + json.dumps(metrics, ensure_ascii=False, separators=(",", ":")) + ";\n"
output += "export function measureSocialText(text, font = 'sans') {\n\tconst widths = SOCIAL_FONT_METRICS[font] || SOCIAL_FONT_METRICS.sans;\n\treturn Array.from(String(text)).reduce((sum, char) => sum + (widths[char] ?? 0.65), 0);\n}\n"
Path("forms/social-font-metrics.mjs").write_text(output, encoding="utf-8")
print("Generated metrics for", ", ".join(fonts))
