/* Η ΑΞΙΑ ΤΗΣ ΓΗΣ ΑΝΑ ΔΟΜΗΣΙΜΟ ΤΕΤΡΑΓΩΝΙΚΟ, παράγωγη.
   €/τ.μ. δόμησης = τιμή πώλησης κατοικίας της περιοχής × μερίδιο γης.
   Επιστρέφει null όταν δεν αναγνωρίζεται η περιοχή — το prompt τότε ξέρει
   ότι δεν έχει άγκυρα, αντί να του δοθεί ένα νούμερο από το πουθενά. */
export function landPricePerBuildableSqm(name) {
	const row = findAreaPrices(name);
	if (!row) return null;
	const zone = AREA_ZONE[row.area] || "regional";
	const share = LAND_SHARE[zone];
	return {
		area: row.area,
		zone,
		low: Math.round((row.saleLow * share.low) / 10) * 10,
		high: Math.round((row.saleHigh * share.high) / 10) * 10,
		sharePct: `${Math.round(share.low * 100)}-${Math.round(share.high * 100)}%`,
		basis: `${row.saleLow}-${row.saleHigh} €/τ.μ. πώλησης κατοικίας × μερίδιο γης`,
	};
}

